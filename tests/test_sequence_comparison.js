'use strict';
const assert=require('assert/strict');
const {buildSequenceComparison}=require('../src/data_sync/sequence_comparison');
const cfg={meter:{rangeKpa:16,accuracyClass:2.5},warnCoef:.5,alarmCoef:1};
const camera=(valueKpa,i=1,status='ok')=>({id:String(i).padStart(32,'0'),valueKpa,status,capturedAt:'2026-10-16T21:00:'+String(i).padStart(2,'0')+'+08:00'});
const reference=(valueKpa,i=1)=>({valueKpa,vendorReceivedAt:'2026-10-16T04:00:'+String(i).padStart(2,'0')+'Z',vendorRecvAtUs:String(1792123200000000+i*1000000)});
const compare=(a,b)=>buildSequenceComparison(a,b,cfg);
assert.deepEqual(compare([],[]),{rows:[],pairedCount:0,latest:null});
let result=compare([camera(4.2)],[reference(4.5)]);
assert.equal(result.rows[0].deltaKpa,-.3);
assert.equal(result.rows[0].percentFS,1.875);
assert.equal(result.rows[0].state,'warning');
assert.equal(result.rows[0].sequence,1);
assert.equal(result.pairedCount,1);
assert.equal(result.latest.sequence,1);
for(const [value,state] of [[.19,'normal'],[.2,'warning'],[.4,'alarm']]){
  result=compare([camera(value)],[reference(0)]);
  assert.equal(result.latest.state,state);
}
result=compare([camera(0)],[reference(0)]);
assert.equal(result.latest.deltaKpa,0);
assert.equal(result.latest.percentFS,0);
assert.equal(result.latest.state,'normal');
const recognition=[camera(4,1),camera(null,2,'failed'),camera(6,3)];
const transmitter=[reference(3,1),reference(4,2),reference(5,3),reference(6,4)];
const original=JSON.stringify([recognition,transmitter]);
result=compare(recognition,transmitter);
assert.equal(result.rows.length,4);
assert.equal(result.rows[1].state,'failed');
assert.equal(result.rows[1].deltaKpa,null);
assert.equal(result.rows[2].recognitionId,recognition[2].id);
assert.equal(result.rows[2].transmitterKpa,5,'failed frames must keep their slot');
assert.equal(result.rows[2].deltaKpa,1);
assert.equal(result.rows[3].pairingStatus,'waiting_recognition');
assert.equal(result.rows[3].deltaKpa,null);
assert.equal(result.pairedCount,2);
assert.equal(result.latest.sequence,3);
assert.equal(JSON.stringify([recognition,transmitter]),original,'raw records must be unchanged');
result=compare([camera(4),camera(5,2),camera(6,3)],[reference(3)]);
assert.equal(result.rows[2].pairingStatus,'waiting_transmitter');
assert.equal(result.rows[2].transmitterKpa,null,'do not reuse latest reference');
assert.equal(result.latest.sequence,1,'latest comparison must identify its own pair');
result=compare([camera(3),camera(5,2),camera(6,3)],[reference(3),reference(null,2),reference(6,3)]);
assert.equal(result.rows[1].state,'review');
assert.equal(result.rows[2].deltaKpa,0,'unknown units must not shift subsequent pairing');
assert.equal(compare([camera(4,1,'需人工复核')],[reference(4)]).latest.state,'review');
assert.equal(compare([camera(20)],[reference(0)]).latest.state,'review');
const before=compare([camera(4,1),camera(5,2)],[reference(3,1),reference(4,2)]);
const after=compare([camera(4,1),camera(5,2),camera(6,3)],[reference(3,1),reference(4,2)]);
assert.deepEqual(after.rows.slice(0,2),before.rows,'appending one side must preserve existing pairs');
const deleted=compare([camera(4,1),camera(6,3)],[reference(3,1),reference(4,2),reference(5,3)]);
assert.equal(deleted.rows[1].recognitionId,camera(6,3).id);
assert.equal(deleted.rows[1].deltaKpa,2,'remaining records are renumbered after deletion');
console.log('PASS: nth-to-nth across different times, signed error, %FS boundaries, zero, gaps, unequal lengths, latest pair, quality flags, append, deletion renumbering and immutable raw records.');
