'use strict';
const assert=require('assert/strict');
const {buildTimeComparison}=require('../src/data_sync/time_comparison');
const cfg={meter:{rangeKpa:16,accuracyClass:2.5},warnCoef:.5,alarmCoef:1,pairingToleranceSeconds:10};
const stamp=s=>new Date(1792470000000+s*1000).toISOString();
const camera=(s,value=8.77,status='ok')=>({id:'c'+s,origin:'camera',capturedAt:stamp(s),valueKpa:value,status});
const reference=(s,value=8.57)=>({vendorRecvAtUs:String(1792470000000000+s*1e6),vendorReceivedAt:stamp(s),valueKpa:value});
let result=buildTimeComparison([camera(0),camera(60),camera(120)],[reference(9),reference(122)],cfg);
assert.equal(result.pairedCount,2);assert.equal(result.rows.find(r=>r.recognitionId==='c60').pairingStatus,'waiting_transmitter');assert.equal(result.rows.find(r=>r.recognitionId==='c120').transmitterRecordedAt,stamp(122));
assert.equal(result.rows[0].deltaKpa,.2);assert.equal(result.rows[0].state,'warning');
assert.equal(buildTimeComparison([camera(0)],[reference(10)],cfg).pairedCount,1);
assert.equal(buildTimeComparison([camera(0)],[reference(10.01)],cfg).pairedCount,0);
assert.equal(buildTimeComparison([camera(0),camera(1)],[reference(0)],cfg).pairedCount,1,'reference cannot be reused');
assert.equal(buildTimeComparison([camera(0,null,'failed')],[reference(0)],cfg).pairedCount,0);
assert.equal(buildTimeComparison([camera(0,8.7,'review')],[reference(0)],cfg).pairedCount,0);
assert.equal(buildTimeComparison([camera(0)],[{...reference(0),timeout:true}],cfg).pairedCount,0);
assert.equal(buildTimeComparison([camera(0,0)],[reference(0,0)],cfg).latest.deltaKpa,0);
assert.equal(buildTimeComparison([camera(0)],[reference(0,null)],cfg).pairedCount,0);
assert.equal(buildTimeComparison([{...camera(0),origin:'offline'}],[reference(0)],cfg).pairedCount,0);
const a=[camera(8),camera(0)],b=[reference(8),reference(-9)];const before=JSON.stringify([a,b]);
assert.equal(buildTimeComparison(a,b,cfg).pairedCount,2,'maximize matches before minimizing time difference');assert.equal(JSON.stringify([a,b]),before);
console.log('PASS: time tolerance, one-to-one assignment, gaps, quality flags, zeros, offline records, chronological matching and immutability');
const triggerCfg={...cfg,recognitionMode:'transmitter'};
const refs=[reference(0),reference(5)];
let bound=buildTimeComparison([{...camera(4),transmitterStamp:refs[0].vendorRecvAtUs,triggerStatus:'recognized'}],refs,triggerCfg);
assert.equal(bound.rows.find(r=>r.recognitionId==='c4').transmitterStamp,refs[0].vendorRecvAtUs,'binding must win over nearest unrelated report');
bound=buildTimeComparison([{...camera(0,null,'缺少历史画面'),transmitterStamp:refs[0].vendorRecvAtUs,triggerStatus:'missing_frame'}],refs,triggerCfg);
assert.equal(bound.pairedCount,0);assert.equal(bound.rows.find(r=>r.recognitionId==='c0').recognitionCapturedAt,null);
console.log('PASS: trigger identity binding and missing-frame timestamps');
